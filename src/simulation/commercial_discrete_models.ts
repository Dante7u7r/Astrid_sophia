/**
 * Busca un modelo discreto comercial por su nombre (sin distinción de mayúsculas).
 */
export function getCommercialDiscreteModel(name: string): ParsedSpiceModel | undefined {
  const norm = name.trim().toUpperCase();
  return ALL_COMMERCIAL_DISCRETE_MODELS.find((m) => m.name.toUpperCase() === norm);
}

/**
 * Obtiene la lista de modelos discretos comerciales filtrados por tipo SPICE.
 */
export function getDiscreteModelsByType(type: "d" | "npn" | "pnp" | "nmos" | "pmos"): readonly ParsedSpiceModel[] {
  const t = type.toLowerCase();
  return ALL_COMMERCIAL_DISCRETE_MODELS.filter((m) => m.type.toLowerCase() === t);
}
